TEST_F(PaintMaterialLayerMaskBakeTest, bake_ensure_writes_row_mask_into_b)
{
  /* The whole path: a mask correction leaves an anchor and B behind, and the baker must fill B
   * with exactly what the composite reads that row's coverage as. */
  PaintMaterialLayerAddParams params;
  params.image_size = 8;
  PaintMaterialLayerEditError error = PaintMaterialLayerEditError::None;
  ASSERT_TRUE(BKE_paint_material_layer_add(*bmain, *material, params, nullptr, &error));
  ASSERT_TRUE(BKE_paint_material_layer_add(*bmain, *material, params, nullptr, &error));
  bUUID correction = {};
  ASSERT_TRUE(BKE_paint_material_layer_correction_add(*bmain,
                                                      *material,
                                                      1,
                                                      PaintMaterialCorrectionSection::Mask,
                                                      PaintMaterialCorrectionEffect::Paint,
                                                      "M",
                                                      &correction,
                                                      &error));

  Image *baked = nullptr;
  for (Image &image : bmain->images) {
    if (image.paint_layer_channel == PAINT_LAYER_MAP_MASK_BAKED) {
      baked = &image;
    }
  }
  ASSERT_NE(baked, nullptr);
  const bUUID marker = baked->paint_layer_id;

  Vector<PaintMaterialCompositeImageLayer> layers;
  ASSERT_TRUE(BKE_paint_material_composite_stack_from_material(
      *bmain, *material, PAINT_MATERIAL_CHANNEL_BASE_COLOR, layers));

  ImBuf *reference = add_output_buffer(8);
  ASSERT_TRUE(BKE_paint_material_composite_eval_row_mask(layers, marker, reference, nullptr));

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));

  void *lock = nullptr;
  ImBuf *ibuf = BKE_image_acquire_ibuf(baked, nullptr, &lock);
  ASSERT_NE(ibuf, nullptr);
  ASSERT_EQ(ibuf->x, reference->x);
  ASSERT_EQ(ibuf->y, reference->y);
  EXPECT_EQ(memcmp(ibuf->byte_data(),
                   reference->byte_data(),
                   size_t(ibuf->x) * ibuf->y * 4),
            0);
  BKE_image_release_ibuf(baked, ibuf, lock);
}

