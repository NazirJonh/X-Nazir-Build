/** \name Bake Cache
 *
 * The lazy half of the baker: a second ensure with nothing changed does no work, and every kind of
 * change -- the graph's description, a source image's pixels, an explicit invalidation -- brings a
 * rebuild back.
 * \{ */

TEST_F(PaintMaterialLayerMaskBakeTest, bake_cache_skips_when_clean)
{
  const BakedRow row = build_baked_row();
  ASSERT_NE(row.baked, nullptr);
  const int channel = PAINT_MATERIAL_CHANNEL_BASE_COLOR;

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));
  const uint64_t first_revision = BKE_paint_material_mask_bake_cache_revision(
      *material, row.row_marker, channel);
  EXPECT_NE(first_revision, 0u);
  EXPECT_TRUE(BKE_paint_material_mask_bake_cache_contains(*material, row.row_marker, channel));

  /* A sentinel the bake cannot produce. Writing it marks no partial update, so only the cache's own
   * dirty state can cause a rewrite; if it does rewrite, the sentinel is gone. */
  fill_image(*row.baked, 17, 17, 17, 255);
  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  EXPECT_EQ(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            first_revision);
  uchar pixel[4] = {0, 0, 0, 0};
  read_pixel(*row.baked, 0, 0, pixel);
  EXPECT_EQ(pixel[0], 17);
  EXPECT_EQ(pixel[3], 255);

  /* Forcing a full rebuild is the way past a clean cache, and it does overwrite the sentinel. */
  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));
  EXPECT_NE(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            first_revision);
  read_pixel(*row.baked, 0, 0, pixel);
  EXPECT_NE(pixel[0], 17);
}

TEST_F(PaintMaterialLayerMaskBakeTest, bake_cache_recomputes_on_structural_change)
{
  const BakedRow row = build_baked_row();
  ASSERT_NE(row.baked, nullptr);
  const int channel = PAINT_MATERIAL_CHANNEL_BASE_COLOR;

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));
  const uint64_t first_revision = BKE_paint_material_mask_bake_cache_revision(
      *material, row.row_marker, channel);
  ASSERT_NE(first_revision, 0u);

  /* Muted directly rather than through the edit API: no commit runs, so the explicit invalidation
   * a public edit would also raise cannot be what rebuilds B. The cache's own structural hash is
   * the only thing that can notice the factor changed. */
  bNode *node = correction_node(row.correction);
  ASSERT_NE(node, nullptr);
  node->flag |= NODE_MUTED;

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  EXPECT_NE(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            first_revision);
}

TEST_F(PaintMaterialLayerMaskBakeTest, bake_cache_recomputes_on_pixel_change)
{
  const BakedRow row = build_baked_row();
  ASSERT_NE(row.baked, nullptr);
  Image *correction = correction_image(row.correction);
  ASSERT_NE(correction, nullptr);
  const int channel = PAINT_MATERIAL_CHANNEL_BASE_COLOR;

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));
  const uint64_t first_revision = BKE_paint_material_mask_bake_cache_revision(
      *material, row.row_marker, channel);
  ASSERT_NE(first_revision, 0u);

  uchar before[4] = {0, 0, 0, 0};
  read_pixel(*row.baked, 0, 0, before);

  /* A dab on the correction's map, recorded the way the paint path records one; the cache learns
   * about it by polling, with nothing told to it. */
  rcti dab;
  BLI_rcti_init(&dab, 0, 2, 0, 2);
  paint_region(*correction, dab, 200);

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  EXPECT_NE(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            first_revision);

  uchar after[4] = {0, 0, 0, 0};
  read_pixel(*row.baked, 0, 0, after);
  EXPECT_NE(memcmp(before, after, sizeof(after)), 0);
}

TEST_F(PaintMaterialLayerMaskBakeTest, bake_cache_invalidate_marks_dirty)
{
  const BakedRow row = build_baked_row();
  ASSERT_NE(row.baked, nullptr);
  const int channel = PAINT_MATERIAL_CHANNEL_BASE_COLOR;

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));
  const uint64_t first_revision = BKE_paint_material_mask_bake_cache_revision(
      *material, row.row_marker, channel);
  ASSERT_NE(first_revision, 0u);

  /* Marked, not dropped: the entry survives so a reader in between keeps its pixels. */
  BKE_paint_material_mask_bake_cache_invalidate(material);
  EXPECT_TRUE(BKE_paint_material_mask_bake_cache_contains(*material, row.row_marker, channel));
  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  const uint64_t second_revision = BKE_paint_material_mask_bake_cache_revision(
      *material, row.row_marker, channel);
  EXPECT_NE(second_revision, first_revision);

  /* The null form is the undo path: every material's entries go dirty at once. */
  BKE_paint_material_mask_bake_cache_invalidate(nullptr);
  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  EXPECT_NE(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            second_revision);

  /* Dropping is the other half: the entry is gone, and the next ensure rebuilds from scratch. */
  BKE_paint_material_mask_bake_cache_free_material(*material);
  EXPECT_FALSE(BKE_paint_material_mask_bake_cache_contains(*material, row.row_marker, channel));
  EXPECT_EQ(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel), 0u);
}

TEST_F(PaintMaterialLayerMaskBakeTest, bake_cache_revision_changes_only_when_written)
{
  const BakedRow row = build_baked_row();
  ASSERT_NE(row.baked, nullptr);
  const int channel = PAINT_MATERIAL_CHANNEL_BASE_COLOR;

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));
  const uint64_t written = BKE_paint_material_mask_bake_cache_revision(
      *material, row.row_marker, channel);
  ASSERT_NE(written, 0u);

  /* Reads that write nothing must not move the revision: a consumer uses it to tell whether its
   * copy of B is still current, and a needless bump would force an upload for nothing. */
  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  EXPECT_EQ(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            written);
  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  EXPECT_EQ(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            written);

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, true));
  const uint64_t rewritten = BKE_paint_material_mask_bake_cache_revision(
      *material, row.row_marker, channel);
  EXPECT_NE(rewritten, written);

  ASSERT_TRUE(BKE_paint_material_mask_bake_ensure(*bmain, *material, false));
  EXPECT_EQ(BKE_paint_material_mask_bake_cache_revision(*material, row.row_marker, channel),
            rewritten);
}

